import 'server-only'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { drawInBox, embedImage, fitText, readForm, tick, wrapText } from './pdf'

// Fills the hospital's paper "Annex-3: Vehicle Requisition Form" (assets/forms/vehicle-requisition.pdf, US Letter
// 612×792 pt). Coordinates were measured once against a 20-pt grid laid over the template.

export type RequisitionData = {
  requester: string // name & ID
  designation: string // designation & dept.
  requestDate: string
  tripDate: string
  reporting: string // time & place
  destination: string
  purpose: string
  passengers: string
  duration: string // duration and ETR
  vehicleType: 'Micro' | 'Ambulance' | 'Car'
  requesterSign?: { data: Buffer; mime: string } | null
  headSign?: { data: Buffer; mime: string } | null
  /** Section B — once the transport section allots a car */
  office?: { available: boolean; vehicleNo: string; driver: string; allottedBy: string; headSign?: { data: Buffer; mime: string } | null } | null
  /** small grey line at the bottom, e.g. "HC-261102-0007 · generated by Unico HomeCare 2 Nov 10:42" */
  footer?: string
  updated?: boolean
}

const DETAILS_X = 226
const DETAILS_W = 316
const INK = rgb(0.05, 0.1, 0.35) // dark blue, reads as "filled in"

export async function fillRequisition(d: RequisitionData) {
  const doc = await PDFDocument.load(await readForm('vehicle-requisition.pdf'))
  const page = doc.getPage(0)
  const font = await doc.embedFont(StandardFonts.Helvetica)
  const bold = await doc.embedFont(StandardFonts.HelveticaBold)
  const row = (y: number, text: string) => fitText(page, text, { x: DETAILS_X, y, maxWidth: DETAILS_W, font, size: 10, color: INK })

  // Section A
  row(648, d.requester)
  row(631, d.designation)
  row(614, d.requestDate)
  row(598, d.tripDate)
  row(581, d.reporting)
  row(565, d.destination)
  wrapText(page, d.purpose, { x: DETAILS_X, y: 548, maxWidth: DETAILS_W, font, size: 9.5, lines: 2, color: INK })
  row(518, d.passengers)
  row(501, d.duration)
  const box: Record<RequisitionData['vehicleType'], number> = { Micro: 226, Ambulance: 279, Car: 353 }
  tick(page, box[d.vehicleType], 483)

  const sign = async (s: { data: Buffer; mime: string } | null | undefined, x: number, y: number, h = 19) => {
    if (!s) return
    const img = await embedImage(doc, s.data, s.mime)
    if (img) drawInBox(page, img, x, y, 80, h)
  }
  await sign(d.requesterSign, 178, 461)
  await sign(d.headSign, 430, 461)

  // Section B
  if (d.office) {
    tick(page, d.office.available ? 226 : 307, 369)
    row(350, d.office.vehicleNo)
    row(328, d.office.driver)
    row(305, d.office.allottedBy)
    await sign(d.office.headSign, 160, 279, 16)
  }

  if (d.updated) page.drawText('UPDATED', { x: 470, y: 712, size: 14, font: bold, color: rgb(0.75, 0.1, 0.1) })
  if (d.footer) fitText(page, d.footer, { x: 92, y: 40, maxWidth: 430, font, size: 7.5, color: rgb(0.45, 0.47, 0.52) })
  return Buffer.from(await doc.save())
}
